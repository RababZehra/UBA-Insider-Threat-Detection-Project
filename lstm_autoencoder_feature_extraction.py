class LstmAutoEncoder(nn.Module):

    def __init__(
        self,
        input_size=25,
        hidden_size=100,
        batch_size=2000,
        encode_size=5
    ):
        super(LstmAutoEncoder, self).__init__()

        self.input_size = input_size
        self.hidden_size = hidden_size
        self.batch_size = batch_size
        self.encode_size = encode_size

        self.encoder_lstm = nn.LSTM(
            self.input_size,
            self.hidden_size,
            batch_first=True
        )

        self.encoder_fc = nn.Linear(
            self.hidden_size,
            self.encode_size
        )

        self.decoder_lstm = nn.LSTM(
            self.hidden_size,
            self.input_size,
            batch_first=True
        )

        self.decoder_fc = nn.Linear(
            self.encode_size,
            self.hidden_size
        )

        self.relu = nn.ReLU()

        self.output_fc = nn.Linear(
            SEQUENCE_LENGTH * self.encode_size,
            N_FEATURES
        )

        self.decoder_input_fc = nn.Linear(
            N_FEATURES,
            SEQUENCE_LENGTH * self.encode_size
        )

    def forward(self, x):

        encoder_lstm, (n, c) = self.encoder_lstm(x)

        encoder_fc = self.encoder_fc(encoder_lstm)

        encoder_out = encoder_fc.flatten(1)

        encoder_out = self.output_fc(encoder_out)

        decoder_input = self.decoder_input_fc(encoder_out)

        decoder_input = decoder_input.view(
            -1,
            SEQUENCE_LENGTH,
            self.encode_size
        )

        decoder_fc = self.decoder_fc(decoder_input)

        decoder_lstm, (n, c) = self.decoder_lstm(decoder_fc)

        return encoder_out, decoder_lstm


class EarlyStopping:

    def __init__(
        self,
        save_path,
        patience=20,
        verbose=True,
        delta=0.0001,
        metric='loss'
    ):
        self.save_path = save_path
        self.patience = patience
        self.verbose = verbose
        self.counter = 0
        self.best_score = None
        self.early_stop = False
        self.val_loss_min = float('inf')
        self.delta = delta
        self.metric = metric
        self.val_bound = float('inf')
        self.sign = -1 if metric == 'loss' else 1

    def __call__(self, value, model):

        value = float(value)
        score = value * self.sign

        if self.best_score is None:

            self.best_score = score
            self.save_checkpoint(value, model)

        elif score < self.best_score + self.delta:

            self.counter += 1

            print(
                f'EarlyStopping counter: '
                f'{self.counter} out of {self.patience}'
            )

            if self.counter >= self.patience:
                self.early_stop = True

        else:

            self.best_score = score
            self.save_checkpoint(value, model)
            self.counter = 0

    def save_checkpoint(self, value, model):

        if self.verbose:

            if self.sign == -1:
                print(
                    f'Validation {self.metric} decreased '
                    f'({self.val_bound:.6f} --> {value:.6f}). '
                    f'Saving model ...'
                )
            else:
                print(
                    f'Validation {self.metric} increased '
                    f'({self.val_bound:.6f} --> {value:.6f}). '
                    f'Saving model ...'
                )

        torch.save(
            model.state_dict(),
            self.save_path
        )

        self.val_bound = value


def save_training_checkpoint(
    path,
    model,
    optimizer,
    epoch,
    early_stopping,
    train_losses,
    validation_losses,
    round_number,
    finished=False
):

    checkpoint = {
        'model_state_dict': model.state_dict(),
        'optimizer_state_dict': optimizer.state_dict(),
        'epoch': epoch,
        'round_number': round_number,
        'early_stopping': {
            'counter': early_stopping.counter,
            'best_score': early_stopping.best_score,
            'early_stop': early_stopping.early_stop,
            'val_loss_min': early_stopping.val_loss_min,
            'val_bound': early_stopping.val_bound
        },
        'train_losses': train_losses,
        'validation_losses': validation_losses,
        'finished': finished,
        'torch_rng_state': torch.get_rng_state(),
        'numpy_rng_state': np.random.get_state(),
        'python_rng_state': random.getstate()
    }

    if torch.cuda.is_available():
        checkpoint['cuda_rng_state_all'] = (
            torch.cuda.get_rng_state_all()
        )

    temporary_path = path + '.tmp'

    torch.save(checkpoint, temporary_path)

    os.replace(temporary_path, path)


def load_training_checkpoint(
    path,
    model,
    optimizer,
    early_stopping
):

    checkpoint = torch.load(
        path,
        map_location=DEVICE,
        weights_only=False
    )

    model.load_state_dict(
        checkpoint['model_state_dict']
    )

    optimizer.load_state_dict(
        checkpoint['optimizer_state_dict']
    )

    state = checkpoint['early_stopping']

    early_stopping.counter = state['counter']
    early_stopping.best_score = state['best_score']
    early_stopping.early_stop = state['early_stop']
    early_stopping.val_loss_min = state['val_loss_min']
    early_stopping.val_bound = state['val_bound']

    torch.set_rng_state(
        checkpoint['torch_rng_state'].cpu()
    )

    np.random.set_state(
        checkpoint['numpy_rng_state']
    )

    random.setstate(
        checkpoint['python_rng_state']
    )

    if (
        torch.cuda.is_available()
        and 'cuda_rng_state_all' in checkpoint
    ):
        torch.cuda.set_rng_state_all(
            checkpoint['cuda_rng_state_all']
        )

    return checkpoint


def save_loss_plot(
    train_losses,
    validation_losses,
    output_path
):

    plt.figure(figsize=(9, 5))

    epochs_completed = range(1, len(train_losses) + 1)

    plt.plot(
        epochs_completed,
        train_losses,
        label='Training loss'
    )

    plt.plot(
        epochs_completed,
        validation_losses,
        label='Monitoring loss'
    )

    if validation_losses:
        best_epoch = int(
            np.argmin(validation_losses)
        ) + 1

        plt.axvline(
            best_epoch,
            linestyle='--',
            label='Lowest monitoring loss'
        )

    plt.xlabel('Epoch')
    plt.ylabel('MSE Loss')
    plt.title('LSTM Autoencoder Training')
    plt.grid(True)
    plt.legend()
    plt.tight_layout()

    plt.savefig(
        output_path,
        dpi=200
    )

    plt.close()


