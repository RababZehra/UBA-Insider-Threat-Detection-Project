class ResHybNet(nn.Module):

    def __init__(self, input_dim, output_dim, cnn='', gnn='', residual=''):
        super(ResHybNet, self).__init__()

        if cnn == '':
            self.mode = 'gnn'
        elif gnn == '':
            self.mode = 'cnn'
        else:
            self.mode = 'hybrid'

        if cnn == 'CNN':
            self.conv1 = nn.Sequential(
                nn.Conv1d(1, 16, kernel_size=3, stride=1, padding=1),
                nn.ReLU(),
                nn.MaxPool1d(kernel_size=2)
            )

            self.conv2 = nn.Sequential(
                nn.Conv1d(16, 32, kernel_size=3, stride=1, padding=1),
                nn.ReLU(),
                nn.MaxPool1d(kernel_size=2)
            )

        if gnn == 'GCN':
            self.gnn1 = GCNConv(input_dim, 16)
            self.gnn2 = GCNConv(16, output_dim)

        elif gnn == 'GAT':
            self.gnn1 = GATConv(input_dim, 16)
            self.gnn2 = GATConv(16, output_dim)

        elif gnn == 'SAGE':
            self.gnn1 = SAGEConv(input_dim, 16)
            self.gnn2 = SAGEConv(16, output_dim)

        if input_dim == 5:
            self.output = nn.Linear(32, 2)
            self.output_g = nn.Linear(5, 2)
        else:
            self.output = nn.Linear(64, 2)
            self.output_g = nn.Linear(10, 2)

        if residual == 'YES':
            self.res = True
        elif residual == 'NO':
            self.res = False

    def forward(self, data):

        x, edge_index = data.x, data.edge_index

        if self.mode == 'cnn':
            x_c = torch.unsqueeze(x, dim=1)
            x_c = self.conv1(x_c)
            x_c = self.conv2(x_c)
            x_c = x_c.view(x_c.size(0), -1)
            out = self.output(x_c)

        elif self.mode == 'gnn':
            x_g = self.gnn1(x, edge_index)
            x_g = F.relu(x_g)
            x_g = F.dropout(x_g, training=self.training)
            x_g = self.gnn2(x_g, edge_index)
            out = self.output_g(x_g)

        else:
            x_g = self.gnn1(x, edge_index)
            x_g = F.relu(x_g)
            x_g = F.dropout(x_g, training=self.training)
            x_g = self.gnn2(x_g, edge_index)

            if self.res:
                x_dual = x + x_g
            else:
                x_dual = x_g

            x_dual = torch.unsqueeze(x_dual, dim=1)
            x_dual = self.conv1(x_dual)
            x_dual = self.conv2(x_dual)
            x_dual = x_dual.view(x_dual.size(0), -1)

            out = self.output(x_dual)

        return F.softmax(out, dim=1)

class EarlyStopping:

    def __init__(
        self,
        save_path,
        patience=30,
        verbose=True,
        delta=0.0001,
        metric='loss'
    ):
        self.save_path = save_path
        self.patience = patience
        self.verbose = verbose
        self.counter = 0
        self.best_score = None
        self.early_stop = False
        self.delta = delta
        self.metric = metric
        self.val_bound = np.inf
        self.sign = -1 if metric == 'loss' else 1

    def __call__(self, value, model):

        value = float(value)
        score = value * self.sign

        if self.best_score is None:
            self.best_score = score
            self.save_checkpoint(value, model)

        elif score < self.best_score + self.delta:
            self.counter += 1

            if self.verbose:
                print(
                    f"EarlyStopping counter: "
                    f"{self.counter} out of {self.patience}"
                )

            if self.counter >= self.patience:
                self.early_stop = True

        else:
            self.best_score = score
            self.save_checkpoint(value, model)
            self.counter = 0

    def save_checkpoint(self, value, model):

        if self.verbose:
            print(
                f"Validation {self.metric}: "
                f"{self.val_bound:.6f} --> {value:.6f}. "
                "Saving model..."
            )

        torch.save(model.state_dict(), self.save_path)
        self.val_bound = value

