for r in trange(TRAIN_ROUNDS):

    print(f"\nTraining round: {r + 1}/{TRAIN_ROUNDS}")

    model = ResHybNet(
        input_dim=data.num_node_features,
        output_dim=data.num_node_features,
        cnn=CNN,
        gnn=GNN,
        residual=RESIDUAL
    ).to(device)

    optimizer = torch.optim.Adam(
        model.parameters(),
        lr=LR,
        weight_decay=WEIGHT_DECAY
    )

    best_model_path = os.path.join(
        MODEL_DIR,
        f"{CNN}_{GNN}_manual+lstm_seq74_{RESIDUAL}_{r}round_best.pt"
    )

    early_stopping = EarlyStopping(
        save_path=best_model_path,
        verbose=True,
        patience=PATIENCE,
        delta=DELTA,
        metric='loss'
    )

    train_loss_s = []
    test_loss_s = []

    for epoch in range(EPOCHS):

        model.train()
        optimizer.zero_grad()

        out = model(data)

        train_log_prob = torch.log(
            out[data.train_mask].clamp_min(1e-12)
        )

        loss = F.nll_loss(
            train_log_prob,
            data.y[data.train_mask]
        )

        loss.backward()
        optimizer.step()

        train_loss_s.append(loss.item())

        model.eval()

        with torch.no_grad():
            out = model(data)

            test_log_prob = torch.log(
                out[data.test_mask].clamp_min(1e-12)
            )

            test_loss = F.nll_loss(
                test_log_prob,
                data.y[data.test_mask]
            )

            test_loss_value = test_loss.item()

            pred = out[data.test_mask].argmax(dim=1)
            true = data.y[data.test_mask]

            test_acc = accuracy_score(
                true.cpu().numpy(),
                pred.cpu().numpy()
            )

        test_loss_s.append(test_loss_value)

        if (epoch + 1) % 10 == 0:
            print(
                f"Epoch {epoch + 1} | "
                f"Train Loss: {loss.item():.6f} | "
                f"Test Loss: {test_loss_value:.6f} | "
                f"Test Accuracy: {test_acc:.4f}"
            )

        early_stopping(test_loss_value, model)

        if early_stopping.early_stop:
            print("Early stopping at epoch:", epoch + 1)
            break

    model.load_state_dict(
        torch.load(
            best_model_path,
            map_location=device,
            weights_only=True
        )
    )

    model.eval()

    with torch.no_grad():
        out = model(data)
        pred = out[data.test_mask].argmax(dim=1)
        true = data.y[data.test_mask]

        y_pred = pred.cpu().numpy()
        y_true = true.cpu().numpy()

    test_acc = accuracy_score(y_true, y_pred)
    test_pre = precision_score(y_true, y_pred, zero_division=0)
    test_rec = recall_score(y_true, y_pred, zero_division=0)
    test_f1 = f1_score(y_true, y_pred, zero_division=0)

    results.append({
        "model": f"{CNN}_{GNN}",
        "features": "manual+lstm_seq74",
        "round": r,
        "test_acc": test_acc,
        "test_pre": test_pre,
        "test_rec": test_rec,
        "test_f1": test_f1,
        "epoch": len(train_loss_s),
        "best_test_loss": min(test_loss_s)
    })

    print(
        f"\nRound {r + 1} results:"
        f"\nAccuracy: {test_acc:.4f}"
        f"\nPrecision: {test_pre:.4f}"
        f"\nRecall: {test_rec:.4f}"
        f"\nF1-score: {test_f1:.4f}"
    )

    plt.figure(figsize=(8, 4))
    plt.plot(train_loss_s, label="Training loss")
    plt.plot(test_loss_s, label="Test loss")
    plt.xlabel("Epoch")
    plt.ylabel("Loss")
    plt.title(f"ResHybNet Round {r + 1}")
    plt.legend()
    plt.tight_layout()
    plt.show()

    del model
    if torch.cuda.is_available():
        torch.cuda.empty_cache()

